'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { pairingURL, createPairingQR, resolveMobileConfig } = require('../mobile-pairing.cjs')

test('QR pairs with the published site, keeps key in fragment and decodes back to the exact URL', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-flow-pair-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const key = 'A'.repeat(43)
  const config = { AGENT_FLOW_REMOTE_ENABLED: '1', AGENT_FLOW_PAIRING_KEY: key }
  const url = new URL(pairingURL(config))
  assert.equal(url.origin, 'https://deotom.github.io')
  assert.equal(url.search, '')
  assert.equal(url.hash, `#pair=${key}`)
  const file = path.join(root, 'agent-flow-supabase.env')
  fs.writeFileSync(file, `AGENT_FLOW_REMOTE_ENABLED=1\nAGENT_FLOW_PAIRING_KEY=${key}\n`)
  assert.equal(resolveMobileConfig({ CODEX_SENSITIVE_DIR: root }), file)
  assert.equal(resolveMobileConfig({ AGENT_FLOW_REMOTE_CONFIG: file }), file)
  const { dataURL } = await createPairingQR(file)
  const { PNG } = require('pngjs')
  const png = PNG.sync.read(Buffer.from(dataURL.split(',')[1], 'base64'))
  const decoded = require('jsqr')(new Uint8ClampedArray(png.data), png.width, png.height)
  assert.equal(decoded.data, url.href)
  assert.throws(() => pairingURL({ ...config, AGENT_FLOW_REMOTE_ENABLED: '0' }), /disabled/)
  assert.throws(() => pairingURL({ ...config, AGENT_FLOW_PAIRING_KEY: 'bad' }), /not configured/)
})
